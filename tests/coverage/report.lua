-- Turns the raw hits recorded by tests/coverage/hook.lua into a line
-- coverage report. Run through tests/coverage/run.sh, not directly.
--
--   lua5.1 tests/coverage/report.lua [--readme README.adoc]
--
-- A line counts as "executable" when the Lua 5.1 compiler emits at least one
-- instruction for it (read from `luac5.1 -l`), so comments, blank lines and
-- the insides of table constructors spanning several lines don't count.
--
-- Writes the full per-file table to tests/coverage/report.txt and prints the
-- per-area summary. With --readme, also rewrites the block between the
-- "// coverage:begin" and "// coverage:end" lines of that AsciiDoc file.

local LUAC = os.getenv("LUAC") or "luac5.1"
local STATS_FILE = os.getenv("DIABOLICUI_COVERAGE_STATS") or "tests/coverage/stats.out"
local REPORT_FILE = "tests/coverage/report.txt"

local function readLines(cmd)
	local pipe = assert(io.popen(cmd))
	local lines = {}
	for line in pipe:lines() do
		lines[#lines + 1] = line
	end
	pipe:close()
	return lines
end

-- Every addon source file: the same set hook.lua records.
local function listSourceFiles()
	local files = readLines("find . -name '*.lua' -not -path './tests/*' -not -path './docs/*' -not -path '*/Libs/*' | sort")
	for i, path in ipairs(files) do
		files[i] = path:gsub("^%./", "")
	end
	return files
end

local function executableLines(path)
	local lines, count = {}, 0
	for _, row in ipairs(readLines(LUAC .. " -p -l '" .. path .. "' 2>/dev/null")) do
		local line = tonumber(row:match("^%s+%d+%s+%[(%d+)%]"))
		if line and line > 0 and not lines[line] then
			lines[line] = true
			count = count + 1
		end
	end
	return lines, count
end

local function readHits()
	local hits = {}
	local file = io.open(STATS_FILE, "r")
	if not file then
		return hits
	end
	for row in file:lines() do
		local path, list = row:match("^([^\t]+)\t(.*)$")
		if path then
			local lines = hits[path] or {}
			hits[path] = lines
			for line in list:gmatch("%d+") do
				lines[tonumber(line)] = true
			end
		end
	end
	file:close()
	return hits
end

-- Report areas: each top-level folder, and each module folder on its own.
local function areaOf(path)
	return path:match("^(modules/[^/]+)/") or path:match("^([^/]+)/") or "(root)"
end

local function percent(covered, total)
	if total == 0 then
		return 100
	end
	return covered * 100 / total
end

local function fmtPercent(covered, total)
	return string.format("%.1f%%", percent(covered, total))
end

local hits = readHits()
local files, areas, areaOrder = {}, {}, {}
local totalCovered, totalLines = 0, 0

for _, path in ipairs(listSourceFiles()) do
	local executable, count = executableLines(path)
	local covered = 0
	local fileHits = hits[path] or {}
	for line in pairs(executable) do
		if fileHits[line] then
			covered = covered + 1
		end
	end
	files[#files + 1] = { path = path, covered = covered, total = count }

	local name = areaOf(path)
	local area = areas[name]
	if not area then
		area = { name = name, covered = 0, total = 0, files = 0 }
		areas[name] = area
		areaOrder[#areaOrder + 1] = area
	end
	area.covered = area.covered + covered
	area.total = area.total + count
	area.files = area.files + 1

	totalCovered = totalCovered + covered
	totalLines = totalLines + count
end

table.sort(areaOrder, function(a, b) return a.name < b.name end)

-- Full per-file report.
local out = assert(io.open(REPORT_FILE, "w"))
out:write(string.format("%-60s %8s %8s %8s\n", "File", "Lines", "Covered", "Percent"))
for _, file in ipairs(files) do
	out:write(string.format("%-60s %8d %8d %8s\n", file.path, file.total, file.covered, fmtPercent(file.covered, file.total)))
end
out:write(string.format("%-60s %8d %8d %8s\n", "TOTAL", totalLines, totalCovered, fmtPercent(totalCovered, totalLines)))
out:close()

-- Summary on stdout.
print(string.format("%-28s %6s %8s %8s %8s", "Area", "Files", "Lines", "Covered", "Percent"))
for _, area in ipairs(areaOrder) do
	print(string.format("%-28s %6d %8d %8d %8s", area.name, area.files, area.total, area.covered, fmtPercent(area.covered, area.total)))
end
print(string.format("%-28s %6d %8d %8d %8s", "TOTAL", #files, totalLines, totalCovered, fmtPercent(totalCovered, totalLines)))
print("\nPer-file report: " .. REPORT_FILE)

-- README block.
local readme
for i = 1, #arg do
	if arg[i] == "--readme" then
		readme = arg[i + 1]
	end
end
if not readme then
	return
end

local function badgeColor(value)
	if value >= 80 then return "brightgreen" end
	if value >= 60 then return "yellowgreen" end
	if value >= 40 then return "yellow" end
	if value >= 20 then return "orange" end
	return "red"
end

local total = percent(totalCovered, totalLines)
local block = {
	"// coverage:begin",
	"// Generated by tests/coverage/run.sh --readme. Don't edit by hand.",
	string.format("image:https://img.shields.io/badge/coverage-%.1f%%25-%s[Line coverage %.1f%%]", total, badgeColor(total), total),
	"",
	string.format("Line coverage of the offline test suite: *%.1f%%* (%d of %d executable lines, %d files, %s).",
		total, totalCovered, totalLines, #files, os.date("%Y-%m-%d")),
	"",
	"[cols=\"3,1,1,1\",options=\"header\"]",
	"|===",
	"|Area |Files |Lines |Covered",
}
for _, area in ipairs(areaOrder) do
	block[#block + 1] = string.format("|`%s` |%d |%d |%s", area.name, area.files, area.total, fmtPercent(area.covered, area.total))
end
block[#block + 1] = string.format("|*Total* |*%d* |*%d* |*%s*", #files, totalLines, fmtPercent(totalCovered, totalLines))
block[#block + 1] = "|==="
block[#block + 1] = "// coverage:end"

local file = assert(io.open(readme, "rb"))
local text = file:read("*a")
file:close()

local eol = text:find("\r\n", 1, true) and "\r\n" or "\n"
local startPos = text:find("// coverage:begin", 1, true)
local _, stopPos = text:find("// coverage:end", 1, true)
if not startPos or not stopPos then
	io.stderr:write(readme .. ": no // coverage:begin / // coverage:end block to update\n")
	os.exit(1)
end

text = text:sub(1, startPos - 1) .. table.concat(block, eol) .. text:sub(stopPos + 1)
file = assert(io.open(readme, "wb"))
file:write(text)
file:close()
print("Updated " .. readme)
